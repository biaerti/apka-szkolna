/** Wybor z przestawiona kolejnoscia, zeby dobra odpowiedz nie stala zawsze w tym samym miejscu. */
function miks(opcje: string[], dobra: string, i: number): string {
  const n = i % opcje.length;
  return wybor([...opcje.slice(n), ...opcje.slice(0, n)], dobra);
}

